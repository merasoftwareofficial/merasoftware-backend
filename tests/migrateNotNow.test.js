const { test, before, after } = require('node:test');
const assert = require('node:assert/strict');
const os = require('node:os');
const path = require('node:path');
const fs = require('node:fs');
const mongoose = require('mongoose');
const { MongoMemoryServer } = require('mongodb-memory-server');
const { FinalMessage } = require('../whatsapp/src/models');
const { migrateNotNow } = require('../scripts/migrateNotNow');
let server;
const backup = path.join(os.tmpdir(), `not-now-migration-${process.pid}.json`);
before(async () => { server = await MongoMemoryServer.create(); await mongoose.connect(server.getUri()); });
after(async () => { await mongoose.disconnect(); await server.stop(); fs.rmSync(backup, { force: true }); });
test('migration is preview-only by default, protects active cycles, keeps history and is repeatable', async () => {
  const leads = mongoose.connection.db.collection('leads');
  const a = new mongoose.Types.ObjectId(), b = new mongoose.Types.ObjectId(), c = new mongoose.Types.ObjectId(), d = new mongoose.Types.ObjectId();
  await leads.insertMany([{ _id: a, status: 'Lazy', followUps: [{ badge: 'Lazy', note: 'old' }] }, { _id: b, status: 'Won', clientBehaviour: 'Tough', clientBehaviourRevision: 2 }, { _id: c, status: 'Tough' }, { _id: d, status: 'Lazy', phone: '9876543210' }]);
  await FinalMessage.collection.insertOne({ leadId: c, status: 'waiting' });
  await FinalMessage.collection.insertOne({ leadId: new mongoose.Types.ObjectId(), status: 'waiting', phone: '919876543210' });
  assert.deepEqual(await migrateNotNow(mongoose.connection.db), { applied: false, candidates: 4, blocked: 2 });
  await assert.rejects(migrateNotNow(mongoose.connection.db, { apply: true, backupFile: backup }), /maintenance/);
  const result = await migrateNotNow(mongoose.connection.db, { apply: true, maintenance: true, backupFile: backup });
  assert.equal(result.changed, 2); assert.equal(result.skipped, 2);
  const first = await leads.findOne({ _id: a }), client = await leads.findOne({ _id: b });
  assert.equal(first.status, 'NotNow'); assert.equal(first.followUps[0].badge, 'Lazy');
  assert.equal(client.status, 'Won'); assert.equal(client.clientBehaviour, 'NotNow'); assert.equal(client.clientBehaviourRevision, 3);
  assert.equal((await leads.findOne({ _id: c })).status, 'Tough');
  assert.equal(JSON.parse(fs.readFileSync(backup)).length, 4);
  assert.deepEqual(await migrateNotNow(mongoose.connection.db), { applied: false, candidates: 2, blocked: 2 });
});
